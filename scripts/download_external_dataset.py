"""Download the external evaluation dataset (Reviewer #1: independent public
dataset, evaluation-only, not used for training/fine-tuning).

Chosen: HttpParamsDataset (Morzeux/HttpParamsDataset), priority (1) of the
three candidates given for this task. MIT license (LICENSE file in the repo).
Columns: payload, length, attack_type (norm/sqli/xss/cmdi/path-traversal), label
(norm/anom). Built from CSIC2010 (benign only) + sqlmap/XSSYA/Vega-generated
attack payloads + FuzzDB, per the repo README -- so it is not purely
independent of CSIC2010 on the benign side, but the attack payloads are
generated by different tools than anything in this repo's training data.

Saves the raw file as-is (no cleaning) to data/external/httpparamsdataset_raw.csv.
"""
import datetime
from pathlib import Path
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
EXTERNAL_DIR = ROOT / 'data' / 'external'
RAW_CSV = EXTERNAL_DIR / 'httpparamsdataset_raw.csv'

SOURCE_URL = 'https://raw.githubusercontent.com/Morzeux/HttpParamsDataset/master/payload_full.csv'
REPO_URL = 'https://github.com/Morzeux/HttpParamsDataset/'
LICENSE = 'MIT (LICENSE file in repo, confirmed 2026-09-18)'


def main():
    EXTERNAL_DIR.mkdir(parents=True, exist_ok=True)
    req = Request(SOURCE_URL, headers={'User-Agent': 'Mozilla/5.0'})
    with urlopen(req, timeout=30) as r:
        data = r.read()

    RAW_CSV.write_bytes(data)
    download_date = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S %z') or datetime.date.today().isoformat()

    print(f"Downloaded {len(data)} bytes from {SOURCE_URL}")
    print(f"Saved to: {RAW_CSV}")
    print(f"Repo: {REPO_URL}")
    print(f"License: {LICENSE}")
    print(f"Download date: {download_date}")


if __name__ == '__main__':
    main()
